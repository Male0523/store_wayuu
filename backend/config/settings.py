# Database
# DATABASE_URL se reserva para producción; desarrollo usa DEV_DATABASE_URL.
DB_ENGINE = env('DB_ENGINE', default='sqlite').strip().lower()
DATABASE_URL = env('DATABASE_URL', default='').strip()
DEV_DATABASE_URL = env('DEV_DATABASE_URL', default='').strip()

# Las pruebas siempre usan SQLite efímera y nunca consultan bases configuradas por URL.
USE_SQLITE_TEST_DATABASE = 'test' in sys.argv

if USE_SQLITE_TEST_DATABASE:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': ':memory:',
        }
    }
elif DJANGO_ENV == 'production':
    if DEV_DATABASE_URL:
        raise ImproperlyConfigured('DEV_DATABASE_URL no se permite en producción.')
    if not DATABASE_URL:
        raise ImproperlyConfigured('DATABASE_URL es obligatoria en producción.')
    DATABASES = {'default': dj_database_url.config(default=DATABASE_URL, conn_max_age=600)}
    if DATABASES['default']['ENGINE'] != 'django.db.backends.postgresql':
        raise ImproperlyConfigured('DATABASE_URL de producción debe apuntar a PostgreSQL.')
elif DJANGO_ENV == 'development':
    if DATABASE_URL:
        raise ImproperlyConfigured(
            'DATABASE_URL está reservada para producción. Usa DEV_DATABASE_URL para desarrollo.'
        )
    if DB_ENGINE == 'sqlite':
        if DEV_DATABASE_URL:
            raise ImproperlyConfigured('Quita DEV_DATABASE_URL o cambia DB_ENGINE a postgresql.')
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': BASE_DIR / 'db.sqlite3',
            }
        }
    elif DB_ENGINE == 'postgresql':
        if not DEV_DATABASE_URL:
            raise ImproperlyConfigured('DEV_DATABASE_URL es obligatoria con DB_ENGINE=postgresql.')
        parsed_dev_url = urlsplit(DEV_DATABASE_URL)
        if parsed_dev_url.scheme not in ('postgres', 'postgresql'):
            raise ImproperlyConfigured('DEV_DATABASE_URL debe usar el esquema PostgreSQL.')
        if parsed_dev_url.hostname not in ('localhost', '127.0.0.1', '::1'):
            raise ImproperlyConfigured('DEV_DATABASE_URL debe apuntar a PostgreSQL local, nunca a producción.')
        DATABASES = {'default': dj_database_url.config(default=DEV_DATABASE_URL, conn_max_age=0)}
        if DATABASES['default']['ENGINE'] != 'django.db.backends.postgresql':
            raise ImproperlyConfigured('DEV_DATABASE_URL no se interpretó como PostgreSQL.')
    elif DB_ENGINE == 'mysql':
        if DEV_DATABASE_URL:
            raise ImproperlyConfigured('DEV_DATABASE_URL PostgreSQL no se puede combinar con DB_ENGINE=mysql.')
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.mysql',
                'NAME': env('DB_NAME', default='wayuu_db'),
                'USER': env('DB_USER', default='root'),
                'PASSWORD': env('DB_PASSWORD', default=''),
                'HOST': env('DB_HOST', default='127.0.0.1'),
                'PORT': env('DB_PORT', default='3306'),
                'OPTIONS': {'charset': 'utf8mb4'},
            }
        }
    else:
        raise ImproperlyConfigured('DB_ENGINE debe ser sqlite, postgresql o mysql en desarrollo.')
else:
    raise ImproperlyConfigured('DJANGO_ENV debe ser development o production.')


